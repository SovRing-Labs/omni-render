"""emit_laws.py — the doctor REBUILDS from Chrome's equations (J 2026-10-06): every Chrome law that oracle_synth.py verified
(rustc on every probe answer) is emitted as Rust into src/oracle_laws.rs — one function per law, symbols as parameters, result in
LayoutUnits (1/64 px). The engine calls them at the matching site behind `patch.oracle_laws`. Generated file: do not edit by hand.
Usage: tools/emit_laws.py   (reads results/oracle/*.json, writes src/oracle_laws.rs)"""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
out = ["// SPDX-License-Identifier: MIT OR Apache-2.0", "//! GENERATED by tools/emit_laws.py from Chrome black-box laws (tools/oracle_synth.py, results/oracle/*.json) — do not edit.",
       "//! Each law was found by the doctor's builder from Chrome's answers alone and verified by rustc on every probe; values in 1/64 px.",
       "#![allow(dead_code, unused_parens)]", ""]
n = 0
for f in sorted((ROOT / "results" / "oracle").glob("*.json")):
    if f.name.endswith(".need.jsonl") or f.name.endswith(".out.jsonl"): continue
    r = json.loads(f.read_text())
    eq, syms, v = r.get("equation_1_64px"), r.get("symbols") or [], r.get("validate") or {}
    if not eq or not r.get("verified_rustc") or (v and v.get("agree") != v.get("of")): continue
    fn = "law_" + re.sub(r"[^a-z0-9]+", "_", r["target"].lower())
    params = ", ".join(f"{s}: i64" for s in syms)
    out.append(f"/// {r['target']}: Chrome = {eq}  (probes {v.get('agree', '?')}/{v.get('of', '?')})")
    out.append(f"pub fn {fn}({params}) -> i64 {{ {eq} }}")
    out.append("")
    n += 1
(ROOT / "src" / "oracle_laws.rs").write_text("\n".join(out))
print(f"{n} laws → src/oracle_laws.rs")
